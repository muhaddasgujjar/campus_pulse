# Hybrid search (Architectural.md Sections 5 and 7): vector search and full-text search over
# APPROVED content only, fused with Reciprocal Rank Fusion, in one round trip.
# - Keyword terms are OR-ed (any matching term counts; more matches rank higher).
# - query_embedding may be NULL (embedding failed): the result is keyword-only (Section 15).
# - similarity (cosine, 0..1) and keyword_rank are returned for the deterministic grader.
HYBRID_SEARCH_SQL = """
create or replace function hybrid_search(
  query_text text,
  query_embedding vector(768),
  match_count integer,
  p_institution uuid,
  p_category text default null,
  rrf_k integer default 60
)
returns table (
  chunk_id uuid,
  content text,
  metadata jsonb,
  entry_id uuid,
  document_id uuid,
  title text,
  category text,
  owner_name text,
  last_verified date,
  expires_at date,
  source_url text,
  similarity double precision,
  vector_rank bigint,
  keyword_rank bigint,
  score double precision
)
language sql
stable
as $$
  with eligible as (
    select
      c.id, c.content, c.metadata, c.entry_id, c.document_id, c.embedding, c.tsv,
      coalesce(k.title, d.title) as title,
      coalesce(k.category, d.category) as category,
      coalesce(k.owner_name, d.owner_name) as owner_name,
      coalesce(k.last_verified, d.last_verified) as last_verified,
      coalesce(k.expires_at, d.expires_at) as expires_at,
      coalesce(k.source_url, d.source_url) as source_url
    from chunks c
    left join kb_entries k on k.id = c.entry_id
    left join documents d on d.id = c.document_id
    where c.institution_id = p_institution
      and coalesce(k.status, d.status) = 'approved'
      and (p_category is null or coalesce(k.category, d.category) = p_category)
  ),
  query_terms as (
    select (
      coalesce(nullif(replace(plainto_tsquery('english', query_text)::text, ' & ', ' | '), ''), '')
    ) as english_q,
    (
      coalesce(nullif(replace(plainto_tsquery('simple', query_text)::text, ' & ', ' | '), ''), '')
    ) as simple_q
  ),
  tsq as (
    select case
      when english_q = '' and simple_q = '' then null
      when english_q = '' then simple_q::tsquery
      when simple_q = '' then english_q::tsquery
      else (english_q::tsquery || simple_q::tsquery)
    end as q
    from query_terms
  ),
  vec as (
    select e.id,
           1 - (e.embedding <=> query_embedding) as similarity,
           row_number() over (order by e.embedding <=> query_embedding) as r
    from eligible e
    where query_embedding is not null and e.embedding is not null
    order by e.embedding <=> query_embedding
    limit match_count * 4
  ),
  kw as (
    select e.id,
           row_number() over (order by ts_rank_cd(e.tsv, tsq.q) desc) as r
    from eligible e, tsq
    where tsq.q is not null and e.tsv @@ tsq.q
    order by ts_rank_cd(e.tsv, tsq.q) desc
    limit match_count * 4
  )
  select
    e.id, e.content, e.metadata, e.entry_id, e.document_id, e.title, e.category,
    e.owner_name, e.last_verified, e.expires_at, e.source_url,
    v.similarity, v.r, kw.r,
    coalesce(1.0 / (rrf_k + v.r), 0) + coalesce(1.0 / (rrf_k + kw.r), 0) as score
  from eligible e
  left join vec v on v.id = e.id
  left join kw on kw.id = e.id
  where v.id is not null or kw.id is not null
  order by score desc
  limit match_count;
$$;
"""
